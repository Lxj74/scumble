"""The host contract as tsc sees it (item 77 step 3, docs/PLAN_ENCAPSULATION.md).

The editor modules the node build ships (tools/build_node.py FILES) call `host.<member>`; the EditorHost typedef in
renderer/editor/host.js is the list of those members with their types, and types/contracts.js checks that the app's
host answers it. This writes types/host_calls.js, a checked file that reads every member the editor uses through the
typedef, so a member the editor calls and the typedef lacks fails `npm run types`. The editor modules themselves are not
`@ts-check`ed, which is why the list is generated rather than checked where the calls are.

    python tools/host_contract.py           write types/host_calls.js
    python tools/host_contract.py --check   exit 1 when the file is stale, or the typedef names a member no editor
                                            module calls (a member belongs in the contract only when the editor calls it)

The `types` gate runs the check before tsc. Plain Python, no node folder needed (build_node.py --check needs one).
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_node as b  # noqa: E402

OUT = os.path.join(b.ROOT, "types", "host_calls.js")
HOST_JS = os.path.join(b.SRC, "host.js")


def editor_calls():
    used = set()
    for name in b.FILES:
        used |= set(b.HOST_USE.findall(b.read(os.path.join(b.SRC, name))))
    used.discard("js")   # "./host.js" in an import line
    return sorted(used)


def typedef_members(text):
    """The member names of the EditorHost typedef: the token after each @property's type, its braces matched."""
    start = text.index("@typedef {Object} EditorHost")
    end = text.index("*/", start)
    block = text[start:end]
    names = []
    for m in re.finditer(r"@property \{", block):
        i, depth = m.end(), 1
        while depth and i < len(block):
            if block[i] == "{":
                depth += 1
            elif block[i] == "}":
                depth -= 1
            i += 1
        n = re.match(r"\s*\[?([A-Za-z_$][\w$]*)", block[i:])
        if n:
            names.append(n.group(1))
    return names


def generated(calls):
    lines = [
        "// @ts-check",
        "// Generated by tools/host_contract.py from the editor modules the node build ships (tools/build_node.py FILES):",
        "// every host.<member> they use, read through the contract's type. A member the editor calls and the EditorHost",
        "// typedef in renderer/editor/host.js lacks is an error here at `npm run types`. Nothing loads this file.",
        "// Do not edit: `python tools/host_contract.py` writes it again.",
        "",
        '/** @param {import("../renderer/editor/host.js").EditorHost} host */',
        "function editorCalls(host) {",
        "    return [",
    ]
    lines += [f"        host.{m}," for m in calls]
    lines += ["    ];", "}", "void editorCalls;", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    calls = editor_calls()
    want = generated(calls)
    if not args.check:
        with open(OUT, "w", encoding="utf-8", newline=chr(10)) as f:
            f.write(want)
        print(f"wrote {os.path.relpath(OUT, b.ROOT)}: {len(calls)} host members the editor calls")
        return
    problems = []
    have = b.read(OUT) if os.path.exists(OUT) else None
    if have != want:
        problems.append("types/host_calls.js is stale: run python tools/host_contract.py")
    typed = typedef_members(b.read(HOST_JS))
    for m in sorted(set(typed) - set(calls)):
        problems.append(f"the EditorHost typedef names {m}, which no editor module calls (it belongs to the app's host alone)")
    for m in sorted({m for m in typed if typed.count(m) > 1}):
        problems.append(f"the EditorHost typedef names {m} twice")
    if problems:
        for p in problems:
            print("PROBLEM", p)
        sys.exit(1)
    print(f"ok: types/host_calls.js holds the {len(calls)} host members the editor calls; the typedef names no other")


if __name__ == "__main__":
    main()
